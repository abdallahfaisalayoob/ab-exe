CANVAS_WIDTH = 720
CANVAS_HEIGHT = 480
DEFAULT_WORK_WIDTH_MM = 120.0
DEFAULT_WORK_HEIGHT_MM = 80.0
DEFAULT_FEED_MM_MIN = 500
DEFAULT_TRAVEL_FEED_MM_MIN = 1200
DEFAULT_POWER = 250
DEFAULT_SAFE_Z_MM = 5.0
DEFAULT_FOCUS_Z_MM = 0.0


@dataclass
class SerialEvent:
    kind: str
    message: str


class GcodeBuilder:
    def __init__(
        self,
        canvas_width: int,
        canvas_height: int,
        work_width_mm: float,
        work_height_mm: float,
        feed_mm_min: int,
        travel_feed_mm_min: int,
        laser_power: int,
        safe_z_mm: float,
        focus_z_mm: float,
    ) -> None:
        self.canvas_width = canvas_width
        self.canvas_height = canvas_height
        self.work_width_mm = work_width_mm
        self.work_height_mm = work_height_mm
        self.feed_mm_min = feed_mm_min
        self.travel_feed_mm_min = travel_feed_mm_min
        self.laser_power = laser_power
        self.safe_z_mm = safe_z_mm
        self.focus_z_mm = focus_z_mm

    def pixel_to_mm(self, x: int, y: int) -> tuple[float, float]:
        mm_x = (x / self.canvas_width) * self.work_width_mm
        mm_y = (y / self.canvas_height) * self.work_height_mm
        return round(mm_x, 3), round(mm_y, 3)

    def build(self, strokes: list[list[tuple[int, int]]]) -> list[str]:
        lines = [
            "; Generated by laser_ui.py",
            "; Verify enclosure, interlocks, ventilation, and focus before running.",
            "G21",
            "G90",
            "M5",
            f"G0 Z{self.safe_z_mm:.3f} F300",
        ]

        for stroke in strokes:
            if len(stroke) < 2:
                continue

            start_x, start_y = self.pixel_to_mm(*stroke[0])
            lines.extend(
                [
                    "M5",
                    f"G0 Z{self.safe_z_mm:.3f} F300",
                    f"G0 X{start_x:.3f} Y{start_y:.3f} F{self.travel_feed_mm_min}",
                    f"G1 Z{self.focus_z_mm:.3f} F300",
                    f"M3 S{self.laser_power}",
                ]
            )

            last_point = stroke[0]
            for point in stroke[1:]:
                if self._distance_px(last_point, point) < 2.0:
                    continue
                x_mm, y_mm = self.pixel_to_mm(*point)
                lines.append(f"G1 X{x_mm:.3f} Y{y_mm:.3f} F{self.feed_mm_min}")
                last_point = point

        lines.extend(["M5", f"G0 Z{self.safe_z_mm:.3f} F300", "M18"])
        return lines

    @staticmethod
    def _distance_px(a: tuple[int, int], b: tuple[int, int]) -> float:
        dx = a[0] - b[0]
        dy = a[1] - b[1]
        return (dx * dx + dy * dy) ** 0.5


class SerialStreamer:
    def __init__(self, event_queue: queue.Queue[SerialEvent]) -> None:
        self.event_queue = event_queue
        self.port = None
        self.stop_event = threading.Event()
        self.worker: threading.Thread | None = None

    @property
    def connected(self) -> bool:
        return self.port is not None and self.port.is_open

    def connect(self, port_name: str, baud: int) -> None:
        if serial is None:
            raise RuntimeError("pyserial is not installed. Run: python -m pip install -r requirements.txt")
        self.close()
        self.port = serial.Serial(port_name, baudrate=baud, timeout=0.2, write_timeout=2)
        time.sleep(2.0)
        self._drain_startup_text()

    def close(self) -> None:
        self.stop_event.set()
        if self.worker and self.worker.is_alive():
            self.worker.join(timeout=1.0)
        self.worker = None
        if self.port and self.port.is_open:
            self.port.close()
        self.port = None

    def send_line(self, line: str) -> None:
        if not self.connected:
            raise RuntimeError("Serial port is not connected.")
        payload = (line.strip() + "\n").encode("ascii", errors="ignore")
        self.port.write(payload)
        self.port.flush()

    def read_available(self) -> list[str]:
        if not self.connected:
            return []
        lines: list[str] = []
        while self.port.in_waiting:
            raw = self.port.readline()
            if not raw:
                break
            line = raw.decode(errors="replace").strip()
            if line:
                lines.append(line)
        return lines

    def stream(self, lines: list[str]) -> None:
        if not self.connected:
            raise RuntimeError("Serial port is not connected.")
        if self.worker and self.worker.is_alive():
            raise RuntimeError("A stream is already running.")

        self.stop_event.clear()
        self.worker = threading.Thread(target=self._stream_worker, args=(lines,), daemon=True)
        self.worker.start()

    def stop(self) -> None:
        self.stop_event.set()
        if self.connected:
            try:
                self.send_line("M112")
            except Exception as exc:
                self.event_queue.put(SerialEvent("error", f"Emergency stop send failed: {exc}"))

    def _drain_startup_text(self) -> None:
        if not self.connected:
            return
        end_at = time.time() + 1.0
        while time.time() < end_at:
            raw = self.port.readline()
            if raw:
                self.event_queue.put(SerialEvent("rx", raw.decode(errors="replace").strip()))

    def _stream_worker(self, lines: list[str]) -> None:
        try:
            total = len([line for line in lines if self._should_send(line)])
            sent = 0
            for raw_line in lines:
                if self.stop_event.is_set():
                    self.event_queue.put(SerialEvent("status", "Stream stopped."))
                    return

                line = raw_line.strip()
                if not self._should_send(line):
                    continue

                sent += 1
                self.event_queue.put(SerialEvent("tx", line))
                self.send_line(line)
                response = self._wait_for_response(timeout=60.0)
                self.event_queue.put(SerialEvent("rx", response))
                self.event_queue.put(SerialEvent("progress", f"{sent}/{total}"))

                if response.startswith("error:") or response.startswith("ALARM:"):
                    self.event_queue.put(SerialEvent("error", f"Controller rejected line: {line} -> {response}"))
                    return

            self.event_queue.put(SerialEvent("status", "Stream complete."))
        except Exception as exc:
            self.event_queue.put(SerialEvent("error", str(exc)))

    @staticmethod
    def _should_send(line: str) -> bool:
        stripped = line.strip()
        return bool(stripped) and not stripped.startswith(";")

    def _wait_for_response(self, timeout: float) -> str:
        deadline = time.time() + timeout
        last_line = ""
        while time.time() < deadline:
            if self.stop_event.is_set():
                return "error:stream_stopped"
            raw = self.port.readline()
            if not raw:
                continue
            line = raw.decode(errors="replace").strip()
            if not line:
                continue
            last_line = line
            if line == "ok" or line.startswith("error:") or line.startswith("ALARM:"):
                return line
            self.event_queue.put(SerialEvent("rx", line))
        return f"error:timeout_waiting_for_ok last={last_line}"


class LaserUi(tk.Tk):
    def __init__(self) -> None:
        super().__init__()
        self.title("XYZ Laser Engraver UI")
        self.geometry("1120x720")
        self.minsize(980, 620)

        self.strokes: list[list[tuple[int, int]]] = []
        self.current_stroke: list[tuple[int, int]] | None = None
        self.generated_gcode: list[str] = []
        self.serial_events: queue.Queue[SerialEvent] = queue.Queue()
        self.streamer = SerialStreamer(self.serial_events)

        self.port_var = tk.StringVar()
        self.baud_var = tk.StringVar(value="115200")
        self.work_w_var = tk.StringVar(value=str(DEFAULT_WORK_WIDTH_MM))
        self.work_h_var = tk.StringVar(value=str(DEFAULT_WORK_HEIGHT_MM))
        self.feed_var = tk.StringVar(value=str(DEFAULT_FEED_MM_MIN))
        self.travel_feed_var = tk.StringVar(value=str(DEFAULT_TRAVEL_FEED_MM_MIN))
        self.power_var = tk.StringVar(value=str(DEFAULT_POWER))
        self.safe_z_var = tk.StringVar(value=str(DEFAULT_SAFE_Z_MM))
        self.focus_z_var = tk.StringVar(value=str(DEFAULT_FOCUS_Z_MM))
        self.progress_var = tk.StringVar(value="Idle")

        self._build_ui()
        self._refresh_ports()
        self.after(100, self._poll_serial_events)
        self.protocol("WM_DELETE_WINDOW", self._on_close)

    def _build_ui(self) -> None:
        self.columnconfigure(0, weight=1)
        self.columnconfigure(1, weight=0)
        self.rowconfigure(0, weight=1)

        canvas_frame = ttk.Frame(self, padding=10)
        canvas_frame.grid(row=0, column=0, sticky="nsew")
        canvas_frame.rowconfigure(0, weight=1)
        canvas_frame.columnconfigure(0, weight=1)

        self.canvas = tk.Canvas(
            canvas_frame,
            width=CANVAS_WIDTH,
            height=CANVAS_HEIGHT,
            bg="#fbfaf5",
            highlightthickness=1,
            highlightbackground="#b8b1a2",
        )
        self.canvas.grid(row=0, column=0, sticky="nsew")
        self.canvas.bind("<ButtonPress-1>", self._start_stroke)
        self.canvas.bind("<B1-Motion>", self._draw_stroke)
        self.canvas.bind("<ButtonRelease-1>", self._end_stroke)

        self._draw_grid()

        side = ttk.Frame(self, padding=10)
        side.grid(row=0, column=1, sticky="ns")

        self._add_machine_controls(side)
        self._add_job_controls(side)
        self._add_gcode_preview(side)
        self._add_log(side)

    def _add_machine_controls(self, parent: ttk.Frame) -> None:
        frame = ttk.LabelFrame(parent, text="Machine", padding=8)
        frame.pack(fill="x", pady=(0, 8))

        ttk.Label(frame, text="Port").grid(row=0, column=0, sticky="w")
        self.port_combo = ttk.Combobox(frame, textvariable=self.port_var, width=18)
        self.port_combo.grid(row=0, column=1, sticky="ew", padx=4)
        ttk.Button(frame, text="Refresh", command=self._refresh_ports).grid(row=0, column=2)

        ttk.Label(frame, text="Baud").grid(row=1, column=0, sticky="w")
        ttk.Entry(frame, textvariable=self.baud_var, width=10).grid(row=1, column=1, sticky="w", padx=4, pady=4)
        ttk.Button(frame, text="Connect", command=self._connect).grid(row=1, column=2, sticky="ew")

        ttk.Button(frame, text="ARM", command=lambda: self._send_manual("ARM")).grid(row=2, column=0, sticky="ew", pady=2)
        ttk.Button(frame, text="DISARM", command=lambda: self._send_manual("DISARM")).grid(row=2, column=1, sticky="ew", pady=2)
        ttk.Button(frame, text="Status", command=lambda: self._send_manual("?")).grid(row=2, column=2, sticky="ew", pady=2)

        ttk.Button(frame, text="RESET Alarm", command=lambda: self._send_manual("RESET")).grid(row=3, column=0, columnspan=2, sticky="ew", pady=2)
        stop_button = tk.Button(frame, text="EMERGENCY STOP", bg="#b00020", fg="white", command=self._emergency_stop)
        stop_button.grid(row=3, column=2, sticky="ew", pady=2)

    def _add_job_controls(self, parent: ttk.Frame) -> None:
        frame = ttk.LabelFrame(parent, text="Job", padding=8)
        frame.pack(fill="x", pady=(0, 8))

        fields = [
            ("Work W mm", self.work_w_var),
            ("Work H mm", self.work_h_var),
            ("Engrave F", self.feed_var),
            ("Travel F", self.travel_feed_var),
            ("Laser S", self.power_var),
            ("Safe Z", self.safe_z_var),
            ("Focus Z", self.focus_z_var),
        ]

        for row, (label, var) in enumerate(fields):
            ttk.Label(frame, text=label).grid(row=row, column=0, sticky="w")
            ttk.Entry(frame, textvariable=var, width=12).grid(row=row, column=1, sticky="ew", padx=4, pady=2)

        ttk.Button(frame, text="Generate Preview", command=self._generate_gcode).grid(row=0, column=2, sticky="ew", padx=(8, 0))
        ttk.Button(frame, text="Export G-code", command=self._export_gcode).grid(row=1, column=2, sticky="ew", padx=(8, 0))
        ttk.Button(frame, text="Load G-code", command=self._load_gcode).grid(row=2, column=2, sticky="ew", padx=(8, 0))
        ttk.Button(frame, text="Stream to Machine", command=self._stream_gcode).grid(row=3, column=2, sticky="ew", padx=(8, 0))
        ttk.Button(frame, text="Clear Drawing", command=self._clear_drawing).grid(row=4, column=2, sticky="ew", padx=(8, 0))
        ttk.Label(frame, textvariable=self.progress_var).grid(row=5, column=2, sticky="w", padx=(8, 0))

    def _add_gcode_preview(self, parent: ttk.Frame) -> None:
        frame = ttk.LabelFrame(parent, text="G-code Preview", padding=8)
        frame.pack(fill="both", expand=True, pady=(0, 8))
        self.gcode_text = tk.Text(frame, width=46, height=12, wrap="none")
        self.gcode_text.pack(fill="both", expand=True)

    def _add_log(self, parent: ttk.Frame) -> None:
        frame = ttk.LabelFrame(parent, text="Serial Log", padding=8)
        frame.pack(fill="both", expand=True)
        self.log_text = tk.Text(frame, width=46, height=10, wrap="word", state="disabled")
        self.log_text.pack(fill="both", expand=True)

    def _draw_grid(self) -> None:
        spacing = 40
        for x in range(0, CANVAS_WIDTH + 1, spacing):
            self.canvas.create_line(x, 0, x, CANVAS_HEIGHT, fill="#e6dfd0")
        for y in range(0, CANVAS_HEIGHT + 1, spacing):
            self.canvas.create_line(0, y, CANVAS_WIDTH, y, fill="#e6dfd0")
        self.canvas.create_text(12, 12, text="Draw here", anchor="nw", fill="#5f5748")

    def _start_stroke(self, event: tk.Event) -> None:
        point = self._clamped_point(event.x, event.y)
        self.current_stroke = [point]
        self.strokes.append(self.current_stroke)

    def _draw_stroke(self, event: tk.Event) -> None:
        if self.current_stroke is None:
            return
        point = self._clamped_point(event.x, event.y)
        last = self.current_stroke[-1]
        if GcodeBuilder._distance_px(last, point) < 2.0:
            return
        self.current_stroke.append(point)
        self.canvas.create_line(last[0], last[1], point[0], point[1], fill="#111111", width=2, capstyle=tk.ROUND)

    def _end_stroke(self, _event: tk.Event) -> None:
        if self.current_stroke and len(self.current_stroke) < 2:
            self.strokes.remove(self.current_stroke)
        self.current_stroke = None

    def _clamped_point(self, x: int, y: int) -> tuple[int, int]:
        width = max(1, self.canvas.winfo_width())
        height = max(1, self.canvas.winfo_height())
        return max(0, min(width, x)), max(0, min(height, y))

    def _builder(self) -> GcodeBuilder:
        canvas_width = max(1, self.canvas.winfo_width())
        canvas_height = max(1, self.canvas.winfo_height())
        return GcodeBuilder(
            canvas_width,
            canvas_height,
            self._float_from_var(self.work_w_var, "Work width"),
            self._float_from_var(self.work_h_var, "Work height"),
            self._int_from_var(self.feed_var, "Engrave feed"),
            self._int_from_var(self.travel_feed_var, "Travel feed"),
            max(0, min(1000, self._int_from_var(self.power_var, "Laser power"))),
            self._float_from_var(self.safe_z_var, "Safe Z"),
            self._float_from_var(self.focus_z_var, "Focus Z"),
        )

    def _generate_gcode(self) -> None:
        if not self.strokes:
            messagebox.showinfo("No drawing", "Draw one or more strokes before generating G-code.")
            return
        try:
            self.generated_gcode = self._builder().build(self.strokes)
        except ValueError as exc:
            messagebox.showerror("Invalid setting", str(exc))
            return
        self._set_gcode_text(self.generated_gcode)
        self.progress_var.set(f"Generated {len(self.generated_gcode)} lines")

    def _export_gcode(self) -> None:
        if not self.generated_gcode:
            self._generate_gcode()
        if not self.generated_gcode:
            return
        path = filedialog.asksaveasfilename(
            defaultextension=".gcode",
            filetypes=[("G-code files", "*.gcode *.nc *.tap"), ("All files", "*.*")],
        )
        if not path:
            return
        Path(path).write_text("\n".join(self.generated_gcode) + "\n", encoding="utf-8")
        self.progress_var.set(f"Saved {Path(path).name}")

    def _load_gcode(self) -> None:
        path = filedialog.askopenfilename(
            filetypes=[("G-code files", "*.gcode *.nc *.tap"), ("All files", "*.*")]
        )
        if not path:
            return
        self.generated_gcode = Path(path).read_text(encoding="utf-8").splitlines()
        self._set_gcode_text(self.generated_gcode)
        self.progress_var.set(f"Loaded {Path(path).name}")

    def _stream_gcode(self) -> None:
        lines = self._current_gcode_lines()
        if not lines:
            messagebox.showinfo("No G-code", "Generate or load G-code first.")
            return
        if not self.streamer.connected:
            messagebox.showerror("Not connected", "Connect to the Arduino serial port first.")
            return

        confirmed = messagebox.askyesno(
            "Safety confirmation",
            "Before streaming: enclosure closed, eye protection on, ventilation running, "
            "interlock/ESTOP tested, material positioned, and laser focus verified?",
        )
        if not confirmed:
            return

        try:
            self.streamer.stream(lines)
            self.progress_var.set("Streaming...")
        except RuntimeError as exc:
            messagebox.showerror("Stream failed", str(exc))

    def _current_gcode_lines(self) -> list[str]:
        text_lines = self.gcode_text.get("1.0", "end").splitlines()
        return text_lines if any(line.strip() for line in text_lines) else self.generated_gcode

    def _set_gcode_text(self, lines: list[str]) -> None:
        self.gcode_text.delete("1.0", "end")
        self.gcode_text.insert("1.0", "\n".join(lines))

    def _clear_drawing(self) -> None:
        self.strokes.clear()
        self.current_stroke = None
        self.canvas.delete("all")
        self._draw_grid()
        self.generated_gcode = []
        self.gcode_text.delete("1.0", "end")
        self.progress_var.set("Drawing cleared")

    def _refresh_ports(self) -> None:
        if list_ports is None:
            self.port_combo["values"] = []
            self._log("pyserial not installed. Install requirements.txt to list ports.")
            return
        ports = [port.device for port in list_ports.comports()]
        self.port_combo["values"] = ports
        if ports and not self.port_var.get():
            self.port_var.set(ports[0])

    def _connect(self) -> None:
        if self.streamer.connected:
            self.streamer.close()
            self.progress_var.set("Disconnected")
            self._log("Disconnected")
            return

        try:
            self.streamer.connect(self.port_var.get(), int(self.baud_var.get()))
        except Exception as exc:
            messagebox.showerror("Connection failed", str(exc))
            return

        self.progress_var.set("Connected")
        self._log(f"Connected to {self.port_var.get()} at {self.baud_var.get()}")

    def _send_manual(self, command: str) -> None:
        if not self.streamer.connected:
            messagebox.showerror("Not connected", "Connect to the Arduino serial port first.")
            return
        try:
            self.streamer.send_line(command)
            self._log(f"> {command}")
            self.after(150, self._drain_manual_responses)
            self.after(500, self._drain_manual_responses)
        except Exception as exc:
            messagebox.showerror("Send failed", str(exc))

    def _emergency_stop(self) -> None:
        self.streamer.stop()
        self.progress_var.set("Emergency stop sent")
        self._log("> M112")

    def _drain_manual_responses(self) -> None:
        try:
            for line in self.streamer.read_available():
                self._log(f"< {line}")
        except Exception as exc:
            self._log(f"ERROR: manual response read failed: {exc}")

    def _poll_serial_events(self) -> None:
        while True:
            try:
                event = self.serial_events.get_nowait()
            except queue.Empty:
                break

            if event.kind == "tx":
                self._log(f"> {event.message}")
            elif event.kind == "rx":
                self._log(f"< {event.message}")
            elif event.kind == "progress":
                self.progress_var.set(event.message)
            elif event.kind == "status":
                self.progress_var.set(event.message)
                self._log(event.message)
            elif event.kind == "error":
                self.progress_var.set("Error")
                self._log(f"ERROR: {event.message}")
                messagebox.showerror("Controller error", event.message)

        self.after(100, self._poll_serial_events)

    def _log(self, message: str) -> None:
        timestamp = time.strftime("%H:%M:%S")
        self.log_text.configure(state="normal")
        self.log_text.insert("end", f"[{timestamp}] {message}\n")
        self.log_text.see("end")
        self.log_text.configure(state="disabled")

    @staticmethod
    def _float_from_var(var: tk.StringVar, label: str) -> float:
        try:
            value = float(var.get())
        except ValueError as exc:
            raise ValueError(f"{label} must be a number.") from exc
        if value < 0:
            raise ValueError(f"{label} must be non-negative.")
        return value

    @staticmethod
    def _int_from_var(var: tk.StringVar, label: str) -> int:
        try:
            value = int(var.get())
        except ValueError as exc:
            raise ValueError(f"{label} must be an integer.") from exc
        if value < 0:
            raise ValueError(f"{label} must be non-negative.")
        return value

    def _on_close(self) -> None:
        self.streamer.close()
        self.destroy()


